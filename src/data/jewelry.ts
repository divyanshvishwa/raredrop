export function getNormalizedJewelryProducts(): Product[] {
  return jewelryCollection.map((j) => {
    const numericPrice =
      typeof j.price === "number"
        ? j.price
        : Number(String(j.price).replace(/[^0-9.]/g, "")) || 0;
    const cleanImages = (j.images || []).filter(
      (img): img is string => typeof img === "string" && img.trim().length > 0
    );
    const mainImg = j.imageUrl || cleanImages[0] || "";

    return {
      id: j.id,
      name: j.name,
      price: numericPrice,
      type: (j.type as "core" | "exclusive") || "core",
      total_quantity: j.total_quantity ?? 100,
      remaining_quantity: j.remaining_quantity ?? 100,
      image_url: mainImg,
      images: cleanImages.length > 0 ? cleanImages : [mainImg],
      drop_id: j.drop_id ?? "accessories",
      sizes: j.sizes && j.sizes.length > 0 ? j.sizes : ["Free Size"],
      category: "Accessories",
      gender: j.gender ?? "Female",
      created_at: j.created_at ?? new Date().toISOString(),
      description: j.description,
    };
  });
}
